import type { RouteSpec } from './types';

const CHAINS = ['solana', 'ethereum', 'base', 'polygon', 'arbitrum'];

const str = (description: string, extra: Record<string, unknown> = {}) => ({ type: 'string', description, ...extra });
const chain = (list = CHAINS) => str(`One of ${list.join(', ')}`, { enum: list });

/** Low-priced GET data tools: one query string in, one JSON object out. */
const tool = (
  id: string,
  path: string,
  price: number,
  summary: string,
  description: string,
  properties: Record<string, unknown>,
  required: string[],
  exampleInput: Record<string, unknown>,
  exampleOutput: Record<string, unknown>,
): RouteSpec => ({
  id,
  method: 'GET',
  path: `/api/v1/data/${path}`,
  priceUnits: usdcToUnits(price),
  summary,
  description,
  input: { in: 'query', schema: { type: 'object', properties, required } },
  output: { type: 'object' },
  example: { input: exampleInput, output: exampleOutput },
});

